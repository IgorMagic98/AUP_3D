# ============================================================================
# system_builder.py
# ============================================================================
# Формирует математическую модель гидравлической сети из JSON.
#
# Неизвестные системы:
#     X = [Q, P, Qout, Qin]
#
# Где:
#     Q    — расходы в трубах, размер M;
#     P    — напоры давления в узлах, размер N;
#     Qout — расходы потребителей, размер n_out;
#     Qin  — расходы источников, размер n_in.
#
# Матричная модель:
#     R @ Q + C @ Qout + S @ Qin = 0
#
# Матрицы:
#     R — инцидентность узлов и труб, N x M;
#     C — подключение потребителей, N x n_out;
#     S — подключение источников, N x n_in.
# ============================================================================

import numpy as np
import jax
import jax.numpy as jnp

# Включаем 64-битную арифметику JAX
jax.config.update("jax_enable_x64", True)

# Значения по умолчанию
DEFAULT_K_SPRINKLER = 0.35
DEFAULT_PRESSURE_TARGET = 30.29


# ============================================================================
# КЛАСС HydraulicSystemBuilder
# ============================================================================
class HydraulicSystemBuilder:

    def __init__(self, json_data):
        # Исходные данные из Three.js / веб-интерфейса
        self.data = json_data
        
        # --------------------------------------------------------------------
        # СЛОВАРИ СООТВЕТСТВИЯ UUID <-> ИНДЕКС
        # --------------------------------------------------------------------
        self.node_uuid_to_idx = {}
        self.idx_to_node_uuid = {}
        self.edge_uuid_to_idx = {}
        self.idx_to_edge_uuid = {}

        # --------------------------------------------------------------------
        # ОСОБЫЕ УЗЛЫ
        # --------------------------------------------------------------------
        # Индексы узлов-потребителей
        self.sprinkler_indices = []

        # Индексы узлов-источников
        self.source_indices = []

        # Количество потребителей и источников
        self.n_out = 0
        self.n_in = 0

        # --------------------------------------------------------------------
        # РАЗМЕРНОСТИ СЕТИ
        # --------------------------------------------------------------------
        self.N = 0  # количество узлов
        self.M = 0  # количество труб

        # --------------------------------------------------------------------
        # МАТРИЦЫ И ВЕКТОРЫ МОДЕЛИ
        # --------------------------------------------------------------------
        self.R = None           # инцидентность N x M
        self.C = None           # потребители N x n_out
        self.S = None           # источники N x n_in

        self.K_out = None       # K-факторы потребителей, n_out
        self.Hst = None         # высоты узлов, N
        self.Lambda = None      # сопротивления труб, M
        self.kvelocity = None   # коэффициенты скорости труб, M

        # --------------------------------------------------------------------
        # ДАННЫЕ ДЛЯ СОЛВЕРА
        # --------------------------------------------------------------------
        self.consumer_list = []
        self.consumer_array = None

        # Срезы блоков вектора неизвестных
        self.q_slice = None
        self.p_slice = None
        self.qout_slice = None
        self.qin_slice = None

        # Общее количество неизвестных
        self.num_vars = 0

        # Функция невязок
        self.residuals_fun = None

        # Целевое минимальное давление на оросителях
        self.pressure_target = json_data['pressure_sprinkler']

    # =========================================================================
    # МЕТОД 1: ПОСТРОЕНИЕ ГРАФА СЕТИ
    # =========================================================================
    def build_graph(self):
        """
        Строит граф сети и заполняет соответствия UUID <-> индекс.
        """

        # Очистка списков на случай повторного вызова
        self.sprinkler_indices.clear()
        self.source_indices.clear()

        # --------------------------------------------------------------------
        # ОБРАБОТКА УЗЛОВ
        # --------------------------------------------------------------------
        for i, n in enumerate(self.data['Node']):

            uuid = str(n['id'])

            # UUID <-> индекс
            self.node_uuid_to_idx[uuid] = i
            self.idx_to_node_uuid[i] = uuid

            # Тип узла
            node_type = str(n.get('type', '')).strip().lower()

            # Потребитель / ороситель
            if node_type == 'sprinkler':
                self.sprinkler_indices.append(i)

            # Источник / насос
            elif node_type == 'source':
                self.source_indices.append(i)

        # --------------------------------------------------------------------
        # ОБРАБОТКА ТРУБ
        # --------------------------------------------------------------------
        edge_list = []

        for e in self.data['Edge']:

            uuid = str(e['id'])
            u_uuid = str(e['start_node'])
            v_uuid = str(e['end_node'])

            # Добавляем ребро, только если оба узла существуют
            if (
                u_uuid in self.node_uuid_to_idx
                and v_uuid in self.node_uuid_to_idx
            ):
                edge_idx = len(edge_list)

                self.edge_uuid_to_idx[uuid] = edge_idx
                self.idx_to_edge_uuid[edge_idx] = uuid

                edge_list.append((u_uuid, v_uuid, e))

        # --------------------------------------------------------------------
        # РАЗМЕРНОСТИ
        # --------------------------------------------------------------------
        self.N = len(self.node_uuid_to_idx)
        self.M = len(edge_list)

        self.n_out = len(self.sprinkler_indices)
        self.n_in = len(self.source_indices)

        # --------------------------------------------------------------------
        # ПРОВЕРКИ КОРРЕКТНОСТИ
        # --------------------------------------------------------------------
        if self.n_in == 0:
            raise ValueError(
                "В сети не найдено ни одного источника."
            )

        if self.n_out == 0:
            raise ValueError(
                "В сети не найдено ни одного оросителя."
            )

    # =========================================================================
    # МЕТОД 2: ПОСТРОЕНИЕ МАТРИЦ МОДЕЛИ
    # =========================================================================
    def build_matrices(self):
        """
        Формирует матрицы R, C, S и векторы параметров из JSON.

        JSON:
            Корень:
                PRESSURE_TARGET

            Node:
                Y_gl
                K_sprinkler

            Edge:
                Length
                k_t
                kvelocity
        """

        # --------------------------------------------------------------------
        # ЦЕЛЕВОЕ ДАВЛЕНИЕ ИЗ КОРНЯ JSON
        # --------------------------------------------------------------------
        self.pressure_target = float(
            self.data.get('PRESSURE_TARGET', self.pressure_target)
        )

        # --------------------------------------------------------------------
        # СОЗДАНИЕ МАССИВОВ
        # --------------------------------------------------------------------
        R = np.zeros((self.N, self.M), dtype=np.float64)
        C = np.zeros((self.N, self.n_out), dtype=np.float64)
        S = np.zeros((self.N, self.n_in), dtype=np.float64)

        Lambda = np.zeros(self.M, dtype=np.float64)
        kvelocity = np.zeros(self.M, dtype=np.float64)

        Hst = np.zeros(self.N, dtype=np.float64)
        K_out = np.zeros(self.n_out, dtype=np.float64)

        # --------------------------------------------------------------------
        # МАТРИЦА ИНЦИДЕНТНОСТИ И ПАРАМЕТРЫ ТРУБ
        # --------------------------------------------------------------------
        for j, (u_uuid, v_uuid, e) in enumerate(
            [
                (str(e['start_node']), str(e['end_node']), e)
                for e in self.data['Edge']
                if str(e['start_node']) in self.node_uuid_to_idx
                and str(e['end_node']) in self.node_uuid_to_idx
            ]
        ):
            ui = self.node_uuid_to_idx[u_uuid]
            vi = self.node_uuid_to_idx[v_uuid]

            # +1 — труба выходит из узла;
            # -1 — труба входит в узел.
            R[ui, j] = 1.0
            R[vi, j] = -1.0

            # Параметры трубы из JSON
            L = float(e.get('Length', 0))
            k_t = float(e.get('k_t', 0))
            Kv = float(e.get('kvelocity', 0))

            # Коэффициент для расчёта скорости:
            #     V = kvelocity * Q
            kvelocity[j] = Kv

            # Сопротивление трубы.
            # k_t берётся из JSON.
            if k_t > 0:
                Lambda[j] = L / k_t
            else:
                raise ValueError(
                    f"У трубы {e.get('id')} задан k_t = 0. "
                    "Расчёт сопротивления невозможен."
                )

        # --------------------------------------------------------------------
        # МАТРИЦА ПОТРЕБИТЕЛЕЙ C
        # --------------------------------------------------------------------
        # Каждый столбец соответствует одному потребителю.
        # +1 ставится в строке узла, к которому подключён потребитель.
        for k, node_idx in enumerate(self.sprinkler_indices):
            C[node_idx, k] = 1.0

            node = self.data['Node'][node_idx]

            # K-фактор конкретного оросителя
            K_out[k] = float(
                node.get('K', DEFAULT_K_SPRINKLER)
            )

        # --------------------------------------------------------------------
        # МАТРИЦА ИСТОЧНИКОВ S
        # --------------------------------------------------------------------
        # Каждый столбец соответствует одному источнику.
        # -1 означает поступление воды в сеть.
        for k, node_idx in enumerate(self.source_indices):
            S[node_idx, k] = -1.0

        # --------------------------------------------------------------------
        # ВЫСОТЫ УЗЛОВ
        # --------------------------------------------------------------------
        for i, n in enumerate(self.data['Node']):
            Hst[i] = float(n.get('Y_gl', 0))

        # --------------------------------------------------------------------
        # СОХРАНЕНИЕ МАТРИЦ
        # --------------------------------------------------------------------
        self.R = jnp.array(R)
        self.C = jnp.array(C)
        self.S = jnp.array(S)

        self.K_out = jnp.array(K_out)
        self.Hst = jnp.array(Hst)
        self.Lambda = jnp.array(Lambda)
        self.kvelocity = jnp.array(kvelocity)

        # --------------------------------------------------------------------
        # СПИСКИ ПОТРЕБИТЕЛЕЙ
        # --------------------------------------------------------------------
        self.consumer_list = list(self.sprinkler_indices)

        self.consumer_array = jnp.array(
            self.sprinkler_indices,
            dtype=jnp.int32
        )

        # --------------------------------------------------------------------
        # ФОРМИРОВАНИЕ УРАВНЕНИЙ
        # --------------------------------------------------------------------
        self.build_equations()

    # =========================================================================
    # МЕТОД 3: ФОРМИРОВАНИЕ СИСТЕМЫ УРАВНЕНИЙ
    # =========================================================================
    def build_equations(self):
        """
        Формирует систему уравнений с явными Qout и Qin.

        Неизвестные:
            X = [Q, P, Qout, Qin]

        Уравнения:
            1. Баланс массы во всех узлах:
                   R @ Q + C @ Qout + S @ Qin = 0

            2. Уравнения энергии в трубах:
                   R.T @ (P + Hst) - hf = 0

            3. Расходы потребителей:
                   Qout_k = K_k * sqrt(P_узла_потребителя)

            4. Заданные давления источников:
                   P_источника = P_source_k
        """

        # --------------------------------------------------------------------
        # ЛОКАЛЬНЫЕ ССЫЛКИ НА МАТРИЦЫ
        # --------------------------------------------------------------------
        R = self.R
        C = self.C
        S = self.S

        K_out = self.K_out
        Hst = self.Hst
        Lambda = self.Lambda

        m = self.M
        n = self.N
        n_out = self.n_out
        n_in = self.n_in

        # Индексы источников в JAX-формате
        source_indices = jnp.array(
            self.source_indices,
            dtype=jnp.int32
        )

        # --------------------------------------------------------------------
        # СРЕЗЫ ВЕКТОРА НЕИЗВЕСТНЫХ
        # --------------------------------------------------------------------
        self.q_slice = slice(0, m)
        self.p_slice = slice(m, m + n)
        self.qout_slice = slice(m + n, m + n + n_out)
        self.qin_slice = slice(m + n + n_out, m + n + n_out + n_in)

        q_slice = self.q_slice
        p_slice = self.p_slice
        qout_slice = self.qout_slice
        qin_slice = self.qin_slice

        # --------------------------------------------------------------------
        # КОЛИЧЕСТВО НЕИЗВЕСТНЫХ
        # --------------------------------------------------------------------
        self.num_vars = m + n + n_out + n_in

        # --------------------------------------------------------------------
        # ФУНКЦИЯ НЕВЯЗОК
        # --------------------------------------------------------------------
        def residuals_fun(X, P_sources):
            """
            X — вектор неизвестных [Q, P, Qout, Qin];
            P_sources — давления источников, размер n_in.
            """

            # ------------------------------------------------------------
            # РАЗДЕЛЕНИЕ НЕИЗВЕСТНЫХ
            # ------------------------------------------------------------
            Q = X[q_slice]
            P = X[p_slice]
            Qout = X[qout_slice]
            Qin = X[qin_slice]

            # ------------------------------------------------------------
            # БАЛАНС МАССЫ ВО ВСЕХ УЗЛАХ
            # ------------------------------------------------------------
            # R @ Q    — баланс по трубам;
            # C @ Qout — отток через потребителей;
            # S @ Qin  — приток от источников, знак минус уже в S.
            mass = R @ Q + C @ Qout + S @ Qin

            # ------------------------------------------------------------
            # ПОТЕРИ НАПОРА В ТРУБАХ
            # ------------------------------------------------------------
            # hf = Lambda * Q * |Q|
            # Q * |Q| сохраняет направление потока.
            hf = Lambda * Q * jnp.abs(Q)
            
            # ------------------------------------------------------------
            # СТАТИЧЕСКИЙ НАПОР
            # ------------------------------------------------------------
            # hf = R.T * Hst            
            hst = R.T @ Hst

            # ------------------------------------------------------------
            # УРАВНЕНИЯ ЭНЕРГИИ
            # ------------------------------------------------------------
            # Пьезометрический напор:
            #     H = P + Hst
            #
            # Для трубы:
            #     (P_start + Hst_start)
            #     - (P_end + Hst_end)
            #     - hf = 0
            energy = R.T @ P - hf+ hst

            # ------------------------------------------------------------
            # УРАВНЕНИЯ ПОТРЕБИТЕЛЕЙ
            # ------------------------------------------------------------
            # C.T @ P извлекает давления только в узлах потребителей.
            P_out = C.T @ P

            # Защита от sqrt(отрицательного числа)
            # на промежуточных итерациях.
            P_out_safe = jnp.maximum(P_out, 1e-6)

            # Qout_k - K_k * sqrt(P_k) = 0
            qout_equations = (
                Qout - K_out * jnp.sqrt(P_out_safe)
            )

            # ------------------------------------------------------------
            # ГРАНИЧНЫЕ УСЛОВИЯ ИСТОЧНИКОВ
            # ------------------------------------------------------------
            # Для одного источника допускается скаляр.
            # Для нескольких источников передаётся вектор.
            P_sources_array = jnp.atleast_1d(
                jnp.asarray(P_sources, dtype=P.dtype)
            )

            # P_источника - P_source_k = 0
            pressure_equations = (
                P[source_indices] - P_sources_array
            )

            # ------------------------------------------------------------
            # ИТОГОВАЯ СИСТЕМА
            # ------------------------------------------------------------
            # N балансов массы
            # + M уравнений энергии
            # + n_out уравнений потребителей
            # + n_in условий давления источников
            return jnp.concatenate([
                mass,
                energy,
                qout_equations,
                pressure_equations
            ])

        self.residuals_fun = residuals_fun

    # =========================================================================
    # МЕТОД 4: РАСЧЁТ СКОРОСТЕЙ ПОСЛЕ РЕШЕНИЯ
    # =========================================================================
    def calculate_velocities(self, Q):
        """
        Рассчитывает скорости в трубах после решения.

        Формула:
            V_j = kvelocity_j * Q_j

        Параметры:
            Q — расходы в трубах, л/с.

        Возвращает:
            V — скорости в трубах, м/с.
        """

        Q_np = np.asarray(Q)
        kvelocity_np = np.asarray(self.kvelocity)

        return kvelocity_np * Q_np

    # =========================================================================
    # МЕТОД 5: ДИАГНОСТИКА МОДЕЛИ
    # =========================================================================
    def diagnose(self):
        """
        Проверяет корректность построенной модели.
        """

        print("=" * 60)
        print("ДИАГНОСТИКА ГИДРАВЛИЧЕСКОЙ МОДЕЛИ")
        print("=" * 60)


        print(f"K_out: {self.K_out}")
        print(f"N узлов: {self.N}")
        print(f"M труб: {self.M}")
        print(f"Потребителей: {self.n_out}")
        print(f"Источников: {self.n_in}")
        print(f"Неизвестных: {self.num_vars}")
        print(f"PRESSURE_TARGET: {self.pressure_target}")

        print(f"\nИндексы оросителей: {self.sprinkler_indices}")
        print(f"Индексы источников: {self.source_indices}")

        print("\nПроверка массивов:")

        arrays = {
            "R": self.R,
            "C": self.C,
            "S": self.S,
            "K_out": self.K_out,
            "Hst": self.Hst,
            "Lambda": self.Lambda,
            "kvelocity": self.kvelocity,
        }

        for name, arr in arrays.items():
            if arr is None:
                print(f"{name}: None")
                continue

            arr_np = np.asarray(arr)

            print(
                f"{name}: shape={arr_np.shape}, "
                f"NaN={np.isnan(arr_np).sum()}, "
                f"Inf={np.isinf(arr_np).sum()}"
            )

        print("=" * 60)